"""Generate explicit RPC methods for editor completion from the public catalog."""
from pathlib import Path
import json


def generate(root: Path) -> None:
    package = root / 'src' / 'fnc_rubika'
    catalog = json.loads((package / 'contracts' / 'rubika-session.catalog.json').read_text(encoding='utf-8'))
    names = sorted(item['operation'] for item in catalog['endpoints'] if item['operation'].isidentifier())
    header = '''"""Explicit public RPC names. Generated by scripts/generate_client_methods.py.

Payload schemas vary by operation. Keyword arguments are forwarded unchanged;
the active contract still determines routing, authentication and operation kind.
"""
from __future__ import annotations

from typing import Any, Mapping
from .models import QueuedOperation


'''
    asynchronous = [header, 'class RubikaMethods:\n', '    async def _call_operation(self, operation: str, payload: Mapping[str, Any], *, wait: bool = True, timeout: float | None = 30) -> Mapping[str, Any] | QueuedOperation:\n        raise NotImplementedError\n']
    synchronous = [header, 'class SyncRubikaMethods:\n', '    def _call_operation(self, operation: str, payload: Mapping[str, Any], *, wait: bool = True, timeout: float | None = 30) -> Mapping[str, Any] | QueuedOperation:\n        raise NotImplementedError\n']
    for name in names:
        signature = f'{name}(self, *, wait: bool = True, timeout: float | None = 30, **payload: Any) -> Mapping[str, Any] | QueuedOperation:'
        asynchronous.append(f'\n    async def {signature}\n        """Call the catalog operation {name}."""\n        return await self._call_operation({name!r}, payload, wait=wait, timeout=timeout)\n')
        synchronous.append(f'\n    def {signature}\n        """Call the catalog operation {name}."""\n        return self._call_operation({name!r}, payload, wait=wait, timeout=timeout)\n')
    (package / 'methods.py').write_text(''.join(asynchronous), encoding='utf-8')
    (package / 'sync_methods.py').write_text(''.join(synchronous), encoding='utf-8')
    print(f'Generated {len(names)} explicit methods for async and sync clients.')


if __name__ == '__main__':
    generate(Path(__file__).resolve().parents[1])
